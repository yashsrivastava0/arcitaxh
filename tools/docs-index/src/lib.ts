// Docs registry: frontmatter validation, link checking, INDEX.md generation.
// Tool code (not packages/core): file system access is expected here.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { posix as path } from 'node:path';
import { Ajv } from 'ajv';
import { parse as parseYaml } from 'yaml';

export interface CategoryEntry {
  id: string;
  folder: string;
  registryOnly?: boolean;
}

export interface CategoriesFile {
  categories: CategoryEntry[];
  ignoredFolders: string[];
  exemptFileNames: string[];
}

export interface Problem {
  file: string;
  message: string;
}

export interface DocEntry {
  path: string;
  title: string;
  category: string;
  type: string;
  status: string;
  updated: string;
}

export interface SourceEntry {
  path: string;
  title: string;
}

export interface DocsResult {
  problems: Problem[];
  docs: DocEntry[];
  sources: SourceEntry[];
  index: string;
}

export interface DocsInput {
  /** POSIX-style relative paths under docs/, mapped to file contents (md only needs content). */
  files: Map<string, string>;
  /** Paths (relative to docs/) of every file that exists, any extension, for link targets. */
  allPaths: Set<string>;
  schema: object;
  categories: CategoriesFile;
}

const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;

export function isRealDate(s: string): boolean {
  const m = DATE_RE.exec(s);
  if (!m) return false;
  const [y, mo, d] = [Number(m[1]), Number(m[2]), Number(m[3])];
  const dt = new Date(Date.UTC(y, mo - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === mo - 1 && dt.getUTCDate() === d;
}

export function splitFrontmatter(text: string): { data: unknown; body: string } | { error: string } {
  const normalised = text.replace(/\r\n/g, '\n');
  if (!normalised.startsWith('---\n')) return { error: 'missing frontmatter (file must start with ---)' };
  const end = normalised.indexOf('\n---\n', 4);
  const endAtEof = normalised.endsWith('\n---') ? normalised.length - 4 : -1;
  const close = end !== -1 ? end : endAtEof;
  if (close === -1) return { error: 'frontmatter is not closed (missing second ---)' };
  const raw = normalised.slice(4, close);
  const body = normalised.slice(close + 5);
  try {
    return { data: parseYaml(raw), body };
  } catch (e) {
    return { error: `frontmatter is not valid YAML: ${(e as Error).message.split('\n')[0]}` };
  }
}

type Classification =
  | { kind: 'ignored' }
  | { kind: 'orphan' }
  | { kind: 'source' }
  | { kind: 'exempt'; category: string }
  | { kind: 'doc'; category: string };

export function classify(rel: string, cfg: CategoriesFile): Classification {
  for (const ig of cfg.ignoredFolders) {
    if (rel === ig || rel.startsWith(`${ig}/`)) return { kind: 'ignored' };
  }
  // Longest folder prefix wins.
  const cat = [...cfg.categories]
    .sort((a, b) => b.folder.length - a.folder.length)
    .find((c) => rel.startsWith(`${c.folder}/`));
  const exempt = cfg.exemptFileNames.includes(path.basename(rel));
  if (!cat) return exempt ? { kind: 'exempt', category: '' } : { kind: 'orphan' };
  if (cat.registryOnly) return { kind: 'source' };
  if (exempt) return { kind: 'exempt', category: cat.id };
  return { kind: 'doc', category: cat.id };
}

/** Markdown links outside fenced and inline code. */
export function extractLinks(body: string): string[] {
  const links: string[] = [];
  let inFence = false;
  for (const line of body.split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;
    const stripped = line.replace(/`[^`]*`/g, '');
    for (const m of stripped.matchAll(/!?\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
      if (m[1]) links.push(m[1]);
    }
  }
  return links;
}

function resolveTarget(fromFile: string, target: string): string | null {
  if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith('#')) return null; // external or anchor
  const clean = decodeURIComponent(target.split('#')[0]!.split('?')[0]!);
  if (clean === '') return null;
  return path.normalize(path.join(path.dirname(fromFile), clean));
}

function targetExists(resolved: string, allPaths: Set<string>): boolean {
  const r = resolved.replace(/\/$/, '');
  if (allPaths.has(r)) return true;
  // a directory exists if any file lives under it
  const prefix = `${r}/`;
  for (const p of allPaths) if (p.startsWith(prefix)) return true;
  return false;
}

function firstHeading(text: string, fallback: string): string {
  const m = /^#\s+(.+)$/m.exec(text.replace(/\r\n/g, '\n'));
  return m?.[1]?.trim() ?? fallback;
}

export function buildIndex(docs: DocEntry[], sources: SourceEntry[], cfg: CategoriesFile): string {
  const lines: string[] = [];
  lines.push('# Docs index');
  lines.push('');
  lines.push('<!-- GENERATED by `pnpm docs:index`. Do not edit by hand; CI fails if this file is out of date. -->');
  lines.push('');
  lines.push(
    'Registry of every document under `docs/` with frontmatter. Read this first, then open only the files you need. Sorted by `updated` (newest first) within each category.',
  );
  lines.push('');
  const total = docs.length + sources.length;
  lines.push(`${total} entries (${docs.length} documents, ${sources.length} source files).`);
  for (const cat of cfg.categories) {
    if (cat.registryOnly) {
      lines.push('');
      lines.push(`## ${cat.id}`);
      lines.push('');
      lines.push('Canonical source documents. No frontmatter; read-only.');
      lines.push('');
      lines.push('| Title | Path |');
      lines.push('|---|---|');
      for (const s of [...sources].sort((a, b) => a.path.localeCompare(b.path))) {
        lines.push(`| ${escapeCell(s.title)} | [${s.path}](./${s.path}) |`);
      }
      continue;
    }
    const inCat = docs.filter((d) => d.category === cat.id);
    if (inCat.length === 0) continue;
    inCat.sort((a, b) => (a.updated === b.updated ? a.path.localeCompare(b.path) : a.updated < b.updated ? 1 : -1));
    lines.push('');
    lines.push(`## ${cat.id}`);
    lines.push('');
    lines.push('| Title | Type | Status | Updated | Path |');
    lines.push('|---|---|---|---|---|');
    for (const d of inCat) {
      lines.push(`| ${escapeCell(d.title)} | ${d.type} | ${d.status} | ${d.updated} | [${d.path}](./${d.path}) |`);
    }
  }
  lines.push('');
  return lines.join('\n');
}

function escapeCell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

export function checkDocs(input: DocsInput): DocsResult {
  const { files, schema, categories } = input;
  // INDEX.md is generated by this tool, so it is always a valid link target (even before the first run).
  const allPaths = new Set(input.allPaths).add('INDEX.md');
  const problems: Problem[] = [];
  const docs: DocEntry[] = [];
  const sources: SourceEntry[] = [];

  // The schema's category enum and categories.json must agree (plus `source`, which has no frontmatter).
  const enumFromSchema: string[] =
    ((schema as { properties?: { category?: { enum?: string[] } } }).properties?.category?.enum ?? []).slice().sort();
  const enumFromCategories = categories.categories
    .filter((c) => !c.registryOnly)
    .map((c) => c.id)
    .sort();
  if (JSON.stringify(enumFromSchema) !== JSON.stringify(enumFromCategories)) {
    problems.push({
      file: 'docs/_meta',
      message: `category enum in frontmatter.schema.json (${enumFromSchema.join(', ')}) does not match categories.json (${enumFromCategories.join(', ')})`,
    });
  }

  const ajv = new Ajv({ allErrors: true, strict: true });
  const validate = ajv.compile(schema);

  for (const rel of [...allPaths].sort()) {
    const c = classify(rel, categories);
    if (c.kind === 'ignored') continue;
    if (c.kind === 'orphan') {
      if (rel.endsWith('.md')) {
        problems.push({ file: rel, message: 'markdown file is outside every category folder (see docs/_meta/categories.json)' });
      }
      continue;
    }
    if (c.kind === 'source') {
      const text = files.get(rel);
      const base = path.basename(rel);
      if (base === 'README.md') continue;
      sources.push({ path: rel, title: text !== undefined && rel.endsWith('.md') ? firstHeading(text, base) : base });
      continue;
    }
    if (!rel.endsWith('.md')) continue; // csv, json, etc. are not registry entries
    const text = files.get(rel);
    if (text === undefined) continue;

    const fm = splitFrontmatter(text);
    if (c.kind === 'exempt') {
      const body = 'error' in fm ? text.replace(/\r\n/g, '\n') : fm.body;
      checkLinks(rel, body, allPaths, problems);
      continue;
    }
    if ('error' in fm) {
      problems.push({ file: rel, message: fm.error });
      continue;
    }
    const data = fm.data as Record<string, unknown> | null;
    if (data === null || typeof data !== 'object' || Array.isArray(data)) {
      problems.push({ file: rel, message: 'frontmatter must be a YAML mapping' });
      continue;
    }
    if (!validate(data)) {
      for (const err of validate.errors ?? []) {
        const where = err.instancePath === '' ? '(root)' : err.instancePath.replace(/^\//, '');
        const extra = err.keyword === 'additionalProperties' ? ` (${(err.params as { additionalProperty: string }).additionalProperty})` : '';
        problems.push({ file: rel, message: `frontmatter ${where}: ${err.message}${extra}` });
      }
      continue;
    }
    const fmData = data as {
      title: string;
      category: string;
      type: string;
      status: string;
      created: string;
      updated: string;
      verified_on: string | null;
      supersedes: string[];
      related: string[];
    };
    if (fmData.category !== c.category) {
      problems.push({ file: rel, message: `category "${fmData.category}" does not match the folder's category "${c.category}"` });
    }
    for (const key of ['created', 'updated'] as const) {
      if (!isRealDate(fmData[key])) problems.push({ file: rel, message: `${key} "${fmData[key]}" is not a real calendar date` });
    }
    if (fmData.verified_on !== null && !isRealDate(fmData.verified_on)) {
      problems.push({ file: rel, message: `verified_on "${fmData.verified_on}" is not a real calendar date` });
    }
    if (isRealDate(fmData.created) && isRealDate(fmData.updated) && fmData.updated < fmData.created) {
      problems.push({ file: rel, message: 'updated is earlier than created' });
    }
    for (const field of ['supersedes', 'related'] as const) {
      for (const t of fmData[field]) {
        const resolved = resolveTarget(rel, t) ?? path.normalize(path.join(path.dirname(rel), t));
        if (!targetExists(resolved, allPaths)) problems.push({ file: rel, message: `${field} target does not exist: ${t}` });
      }
    }
    checkLinks(rel, fm.body, allPaths, problems);
    docs.push({ path: rel, title: fmData.title, category: fmData.category, type: fmData.type, status: fmData.status, updated: fmData.updated });
  }

  return { problems, docs, sources, index: buildIndex(docs, sources, categories) };
}

function checkLinks(rel: string, body: string, allPaths: Set<string>, problems: Problem[]): void {
  for (const link of extractLinks(body)) {
    const resolved = resolveTarget(rel, link);
    if (resolved === null) continue;
    if (resolved.startsWith('..')) continue; // points outside docs/; checked by humans and by git, not here
    if (!targetExists(resolved, allPaths)) problems.push({ file: rel, message: `broken relative link: ${link}` });
  }
}

/** Reads docs/ from disk into a DocsInput. */
export function loadDocsInput(docsDir: string): DocsInput {
  const files = new Map<string, string>();
  const allPaths = new Set<string>();
  const walk = (abs: string, rel: string): void => {
    for (const name of readdirSync(abs)) {
      if (name === 'node_modules' || name === '.git') continue;
      const a = `${abs}/${name}`;
      const r = rel === '' ? name : `${rel}/${name}`;
      if (statSync(a).isDirectory()) walk(a, r);
      else {
        allPaths.add(r);
        if (r.endsWith('.md')) files.set(r, readFileSync(a, 'utf8'));
      }
    }
  };
  walk(docsDir, '');
  const schema = JSON.parse(readFileSync(`${docsDir}/_meta/frontmatter.schema.json`, 'utf8')) as object;
  const categories = JSON.parse(readFileSync(`${docsDir}/_meta/categories.json`, 'utf8')) as CategoriesFile;
  return { files, allPaths, schema, categories };
}

export function indexIsCurrent(docsDir: string, generated: string): boolean {
  const p = `${docsDir}/INDEX.md`;
  if (!existsSync(p)) return false;
  return readFileSync(p, 'utf8').replace(/\r\n/g, '\n') === generated;
}
