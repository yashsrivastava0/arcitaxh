// THIRD_PARTY_NOTICES.md generation. Pure: the CLI reads the files and passes text in.

export interface NoticePackage {
  name: string;
  version: string;
  license: string;
  homepage: string | null;
  licenseText: string | null;
  noticeText: string | null;
}

const norm = (s: string): string => s.replace(/\r\n/g, '\n').trim();

export function buildNotices(packages: NoticePackage[]): string {
  const sorted = [...packages].sort((a, b) =>
    a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name),
  );
  const out: string[] = [];
  out.push('# Third-party notices');
  out.push('');
  out.push('<!-- GENERATED by `pnpm notices`. Do not edit by hand; CI fails if this file is out of date. -->');
  out.push('');
  if (sorted.length === 0) {
    out.push(
      'No third-party software is shipped in the production build yet. Development tools are not distributed and are not listed here; their licences are recorded in `docs/03-specs/licence-register.md`.',
    );
    out.push('');
    return out.join('\n');
  }
  out.push(
    'This product includes the third-party software listed below. Each is used under the licence shown. Development tools are not distributed and are recorded in `docs/03-specs/licence-register.md`.',
  );
  out.push('');
  out.push('## Packages');
  out.push('');
  out.push('| Package | Version | Licence | Homepage |');
  out.push('|---|---|---|---|');
  for (const p of sorted) out.push(`| ${p.name} | ${p.version} | ${p.license} | ${p.homepage ?? ''} |`);
  out.push('');

  // Group identical licence texts so MIT is not repeated hundreds of times.
  const groups = new Map<string, { license: string; names: string[] }>();
  const missing: string[] = [];
  for (const p of sorted) {
    if (p.licenseText === null || norm(p.licenseText) === '') {
      missing.push(`${p.name}@${p.version}`);
      continue;
    }
    const key = norm(p.licenseText);
    const g = groups.get(key) ?? { license: p.license, names: [] };
    g.names.push(`${p.name}@${p.version}`);
    groups.set(key, g);
  }
  out.push('## Licence texts');
  out.push('');
  for (const [text, g] of groups) {
    out.push(`### ${g.license} (${g.names.length} package${g.names.length === 1 ? '' : 's'})`);
    out.push('');
    out.push(`Applies to: ${g.names.join(', ')}`);
    out.push('');
    out.push('```text');
    out.push(text);
    out.push('```');
    out.push('');
  }
  if (missing.length > 0) {
    out.push('## Packages with no licence file found in the package');
    out.push('');
    out.push(
      'The licence of each is stated in the table above (read from the package metadata). A licence text must be added before release: ' +
        missing.join(', '),
    );
    out.push('');
  }
  const notices = sorted.filter((p) => p.noticeText !== null && norm(p.noticeText) !== '');
  if (notices.length > 0) {
    out.push('## NOTICE files');
    out.push('');
    for (const p of notices) {
      out.push(`### ${p.name}@${p.version}`);
      out.push('');
      out.push('```text');
      out.push(norm(p.noticeText as string));
      out.push('```');
      out.push('');
    }
  }
  return out.join('\n');
}
